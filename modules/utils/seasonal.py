"""Сезонный круг года (8 врат) - контент-календарь для бота и автопостера.

Возвращает контекст ближайшего врата года, если сегодня в окне события
(сам день и 1 день после). Используется в шёпоте звёзд, Карте дня
и автопостере: сезонные посты собирают заметно больше вовлеченности.
"""

import datetime

# (месяц, день): (название, энергия врата, акцент для контента)
SEASONAL_GATES = {
    (2, 1): ("Имболк", "Огонь пробуждения", "первые ростки планов, чистка пространства перед новым циклом"),
    (3, 21): ("Остара (Весеннее равноденствие)", "Баланс света", "точка равновесия: что пора уравновесить в жизни"),
    (5, 1): ("Белтейн", "Пламя союза", "страсть, союзы и смелые шаги навстречу желаемому"),
    (6, 21): ("Лита (Летнее солнцестояние)", "Пик света", "кульминация сил: день, когда намерения звучат громче всего"),
    (8, 1): ("Лугнасад", "Первый урожай", "плоды того, что посеяно весной: время благодарности и сбора"),
    (9, 23): ("Мабон (Осеннее равноденствие)", "Баланс тени", "второе равновесие года: отпускание лишнего перед спуском внутрь"),
    (10, 31): ("Самайн", "Завеса тонка", "встреча с предками и глубокой памятью рода, тени и дары подсознания"),
    (12, 21): ("Йоль (Зимнее солнцестояние)", "Рождение света", "самая долгая ночь: посев намерений в темноту перед рассветом"),
}

_WINDOW_DAYS = 1  # сам день + 1 день после


def get_seasonal_context(now: datetime.datetime = None) -> dict | None:
    """Возвращает {'name', 'energy', 'accent'} ближайшего врата или None.

    Окно: сам день события и один день после (для смены timezone-поясов).
    """
    if now is None:
        now = datetime.datetime.now(datetime.timezone.utc)
    today = now.date()
    for (month, day), (name, energy, accent) in SEASONAL_GATES.items():
        gate_date = datetime.date(today.year, month, day)
        if gate_date <= today <= gate_date + datetime.timedelta(days=_WINDOW_DAYS):
            return {"name": name, "energy": energy, "accent": accent}
    return None


def seasonal_prompt_line(now: datetime.datetime = None) -> str:
    """Готовая строка для промпта ИИ или пустая строка, если врат нет."""
    gate = get_seasonal_context(now)
    if not gate:
        return ""
    return (
        f" СЕЗОННЫЙ КОНТЕКСТ: сегодня {gate['name']} ({gate['energy']}). "
        f"Акцент врата: {gate['accent']}. Тонко вплети это в текст, без лекций."
    )


def seasonal_post_line(now: datetime.datetime = None) -> str:
    """Строка для поста автопостера или пустая строка."""
    gate = get_seasonal_context(now)
    if not gate:
        return ""
    return (
        f" СЕЗОННЫЙ КОНТЕКСТ: сегодня {gate['name']} - врата {gate['energy']}. "
        f"Вплети энергию врата ({gate['accent']}) в содержание поста органично, "
        "это не объявление, а фон."
    )
